    private void eliminarBtn1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_eliminarBtn1ActionPerformed
        Tarea seleccionada = obtenerTareaSeleccionada(true);
if (seleccionada == null) return;

int op = javax.swing.JOptionPane.showConfirmDialog(this,
        "¿Eliminar \"" + seleccionada.getTitulo() + "\"?",
        "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
if (op != javax.swing.JOptionPane.YES_OPTION) return;

try {
    ConexionAPI.eliminarTarea(seleccionada.getId());
    cargarTareas();
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error al eliminar:\n" + e.getMessage(),
            "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_eliminarBtn1ActionPerformed

