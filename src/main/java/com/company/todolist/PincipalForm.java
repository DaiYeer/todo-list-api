    public void cargarTareas() {
    try {
        modeloLista.clear();
        tareasActuales = ConexionAPI.obtenerTareas();
        for (Tarea t : tareasActuales) {
            modeloLista.addElement(t.toString());
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Error al cargar tareas:\n" + e.getMessage(),
                "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}

private Tarea obtenerTareaSeleccionada(boolean mostrarAviso) {
    int idx = tareasList.getSelectedIndex();
    if (idx < 0 || idx >= tareasActuales.size()) {
        if (mostrarAviso) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una tarea de la lista.");
        }
        return null;
    }
    return tareasActuales.get(idx);
}

