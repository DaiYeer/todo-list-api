    private void confirmarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmarBtnActionPerformed
        String titulo = tareaNombreField.getText().trim();
String descripcion = editText.getText();
String hora = horaField.getText().trim();

if (titulo.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "El nombre de la tarea es obligatorio.");
    return;
}

try {
    if (tareaEditar == null) {
        Tarea nueva = new Tarea(0, titulo, descripcion, hora, false);
        ConexionAPI.crearTarea(nueva);
    } else {
        tareaEditar.setTitulo(titulo);
        tareaEditar.setDescripcion(descripcion);
        tareaEditar.setHora(hora);
        ConexionAPI.actualizarTarea(tareaEditar);
    }

    if (principal != null) {
        principal.cargarTareas();
    }
    dispose();
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error al guardar:\n" + e.getMessage(),
            "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_confirmarBtnActionPerformed

